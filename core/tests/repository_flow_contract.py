"""Real C ABI retained refresh effects and async receipt/progress boundaries."""
import json
from network_contract import NetworkContract
class RepositoryFlowContract(NetworkContract):
    def flow(self,method,**args):
        return self.success('mediaRepository.flow.'+method,payloadJSON=json.dumps(args,ensure_ascii=False))
    def start(self,kind,**args):return self.flow('start',kind=kind,now=1.125,**args)
    def resume(self,step,response=None,now=4.125):
        return self.flow('resume',token=step['token'],sequence=step['sequence'],now=now,responseJSON=json.dumps(response,ensure_ascii=False))
    def item(self,id):return dict(id=id,name='作品',kind='movie',year=9223372036854775807)
    def test_home_sequence_empty_success_cancelled_sections_and_preserved_previous_source(self):
        content=dict(libraries=[],resume=[self.item('é')],nextUp=[self.item('old')],latest=[])
        previous=dict(value=content,source='disk',fetchedAt=-10.125)
        s=self.start('home',previous=previous)
        failure=dict(message='offline',isConnectivity=True)
        s=self.resume(s,dict(libraries=dict(failure=failure),resume=dict(failure=failure),nextUp={},latest={}))
        self.assertEqual(s['effect'],'commitHome');self.assertEqual(s['arguments']['home']['snapshot'],previous)
        s=self.resume(s);self.assertTrue(s['done']);self.assertEqual(self.success('mediaRepository.flow.stats')['active'],0)
        s=self.start('home',previous=previous)
        s=self.resume(s,dict(libraries=dict(value=[]),resume=dict(value=[]),nextUp=dict(value=[self.item('n')]),latest={}))
        for effect,response in [('saveLibraries',None),('saveHome_resume',[]),('saveHome_nextUp',[self.item('n')])]:
            self.assertEqual(s['effect'],effect);s=self.resume(s,response)
        result=s['arguments']['home'];self.assertEqual(result['snapshot']['value']['resume'],[])
        self.assertEqual(result['snapshot']['source'],'network');self.assertNotIn('nextUp',result['failures'])
        self.assertEqual(self.server.records,[])
    def test_page_persistence_receipts_and_intervening_final_progress(self):
        descriptor=dict(parentID='lib',recursive=True,kinds=['series','movie','movie'],sortField='year',ascending=False)
        s=self.start('page',descriptor=descriptor,startIndex=0,limit=1)
        token=s['token'];first=s.copy()
        invalid=self.call('mediaRepository.flow.resume',payloadJSON=json.dumps(dict(token=token,sequence=s['sequence'],now=2,responseJSON='{}')))
        self.assertFalse(invalid['ok']);self.assertEqual(invalid['code'],1002)
        s=self.resume(s,dict(items=[self.item('é')],startIndex=0,totalRecordCount=9223372036854775807))
        stale=self.call('mediaRepository.flow.resume',payloadJSON=json.dumps(dict(token=token,sequence=first['sequence'],now=2,responseJSON='{}')))
        self.assertFalse(stale['ok']);self.assertEqual(stale['code'],1002)
        s=self.resume(s,[self.item('é')]);self.assertEqual(s['effect'],'publishPage')
        s=self.resume(s);self.assertEqual(s['effect'],'savePage')
        self.assertEqual(s['arguments']['key']['kinds'],'movie,movie,series')
        self.success('mediaRepository.progress.beginFinal',payloadJSON=json.dumps(dict(item=self.item('e\u0301'),recordedAt=3,positionSeconds=42)))
        s=self.resume(s);self.assertEqual(s['arguments']['pageContent']['items'][0]['playState']['positionSeconds'],42)
        s=self.resume(s);self.assertEqual(s['result']['value']['totalCount'],9223372036854775807)
        self.assertTrue(s['done']);self.assertEqual(self.success('mediaRepository.flow.stats')['active'],0)
    def test_detail_retry_canonical_season_fallback_and_cancel_retirement(self):
        s=self.start('detail',itemID='series')
        s=self.resume(s,dict(id='series',kind='series'));self.assertEqual(s['effect'],'reloadDetail')
        previous=dict(item=dict(id='series',kind='series'),seasons=[dict(id='é',seasonNumber=1)],episodesSeasonID='e\u0301',episodes=[self.item('cached')],collectionMembers=[])
        s=self.resume(s,previous);self.assertEqual(s['effect'],'loadSeries')
        s=self.resume(s,dict(item=dict(id='series',kind='series'),seasons={}))
        self.assertEqual(s['effect'],'loadDetailEpisodes');self.assertEqual(s['arguments']['seasonID'],'é')
        s=self.resume(s,{});self.assertEqual(s['arguments']['detail']['episodes'],previous['episodes'])
        s=self.resume(s);self.assertTrue(s['done']);self.assertEqual(s['result']['failures'],{})
        s=self.start('episodes',seriesID='s',seasonID='a')
        self.success('mediaRepository.progress.invalidate',discardLocalProgress=False)
        self.assertEqual(self.success('mediaRepository.flow.stats')['active'],1)
        self.assertTrue(self.flow('cancel',token=s['token'])['cancelled'])
        self.assertFalse(self.flow('cancel',token=s['token'])['cancelled'])
        for args in [dict(kind='detail',itemID='i',kindHint='BAD'),dict(kind='page',descriptor=dict(recursive='true'),startIndex=0,limit=1),dict(kind='page',descriptor=dict(recursive=True,kinds=['BAD']),startIndex=0,limit=1)]:
            result=self.call('mediaRepository.flow.start',payloadJSON=json.dumps(dict(now=1,**args)))
            self.assertFalse(result['ok']);self.assertEqual(result['code'],1002)
        self.assertEqual(self.success('mediaRepository.flow.stats')['active'],0)
    def test_cache_nil_memory_and_disk_effect_sequences_preserve_full_row_age(self):
        s=self.start('cachedHome');s=self.resume(s)
        self.assertTrue(s['done']);self.assertIsNone(s['result'])
        self.success('mediaRepository.put',bucket='items',payloadJSON=json.dumps(dict(key='é',entry=dict(value=self.item('e\u0301'),fetchedAt=-10.125))))
        s=self.start('cachedItem',itemID='é');self.assertTrue(s['done']);self.assertEqual(s['result']['source'],'memory')
        self.assertEqual(self.success('mediaRepository.flow.stats')['active'],0)
        s=self.start('cachedPage',descriptor=dict(parentID='lib',recursive=True),startIndex=0,limit=1)
        s=self.resume(s,[dict(items=[self.item('first')],startIndex=0,limit=1,fetchedAt=10),dict(items=[self.item('gap')],startIndex=2,limit=1,fetchedAt=-100.125)])
        self.assertEqual(s['effect'],'commitCachedPage');self.assertEqual(s['arguments']['pageSnapshot']['fetchedAt'],-100.125)
        self.assertEqual(s['arguments']['pageSnapshot']['value']['items'],[self.item('first')])
        s=self.resume(s);self.assertTrue(s['done']);self.assertEqual(s['result']['source'],'disk')
        s=self.start('cachedDetail',itemID='series',hasStore=True)
        s=self.resume(s,dict(item=dict(id='series',kind='series'),fetchedAt=1))
        self.assertEqual(s['effect'],'readCachedSeasons')
        s=self.resume(s,[dict(id='special',seasonNumber=0),dict(id='missing')])
        self.assertEqual(s['effect'],'readDetailCachedEpisodes');self.assertEqual(s['arguments']['seasonID'],'missing')
        s=self.resume(s);self.assertEqual(s['effect'],'commitCachedDetail')
        s=self.resume(s);self.assertTrue(s['done']);self.assertEqual(s['result']['value']['episodes'],[])
        self.assertEqual(self.server.records,[])
    def test_prefetch_memory_short_circuit_and_collection_descriptor_keep_native_plan(self):
        s=self.start('prefetch',itemID='item',kindHint='series')
        self.assertEqual(s['effect'],'loadPrefetchCache')
        s=self.resume(s,dict(value=dict(item=self.item('item')),source='memory',fetchedAt=1))
        self.assertTrue(s['done']);self.assertEqual(s['result'],{})
        s=self.start('prefetch',itemID='item',kindHint='series')
        s=self.resume(s)
        self.assertEqual(s['effect'],'loadPrefetchDetail');self.assertEqual(s['arguments']['kindHint'],'series')
        s=self.resume(s);self.assertTrue(s['done'])
        self.assertEqual(self.flow('collectionDescriptor',itemID='c'),dict(parentID='c',recursive=False,sortField='year',ascending=True))
for name in list(vars(NetworkContract)):
    if name.startswith('test_'):setattr(RepositoryFlowContract,name,None)
