    private static func append(loop: [CGPoint], to path: inout Path) {
        guard let first = loop.first else { return }
        path.move(to: first)
        for point in loop.dropFirst() {
            path.addLine(to: point)
        }
        path.closeSubpath()
    }

    // MARK: - 构建

    private static func points(_ flat: [CGFloat]) -> [CGPoint] {
        stride(from: 0, to: flat.count, by: 2).map { index in
            CGPoint(x: flat[index], y: flat[index + 1])
        }
    }

    /// 密折线 → `Path`。`closed` 时收尾 `closeSubpath()`（描摹环都是闭合的）。
    public static func path(_ points: [CGPoint], closed: Bool) -> Path {
        var path = Path()
        guard let first = points.first else { return path }
        path.move(to: first)
        for point in points.dropFirst() {
            path.addLine(to: point)
        }
        if closed {
            path.closeSubpath()
        }
        return path
    }
