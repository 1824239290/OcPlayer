#!/usr/bin/env bash
set -euo pipefail

# Build the Core-enabled native client with the macOS PQ presentation fix.
# Inputs remain untouched; every source/build/library is staged in a new folder.
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
native_root="${1:?Usage: build-macos-hdr-fixed.sh native-OcPlayer liberika-checkout new-output-directory}"
kernel_root="${2:?A liberika checkout with the v0.3.6 tag and bundled native dependencies is required}"
output="${3:?A new output directory is required}"
base=e38a511561cb30ca57bd370b944d2e99b12737c7
patch="$repo_root/patches/liberika/v0.3.6-macos-hdr.patch"
[[ ! -e "$output" ]] || { echo 'Output already exists; choose a new directory.' >&2; exit 1; }
[[ -f "$native_root/OcPlayer.xcodeproj/project.pbxproj" && -d "$kernel_root/third_party/dist" ]] || {
  echo 'Native source and the liberika bundled dependency directory are required.' >&2; exit 1;
}
[[ "$(git -C "$kernel_root" rev-parse 'v0.3.6^{commit}')" == "$base" ]] || {
  echo 'Unexpected liberika base; refusing to apply a version-specific patch.' >&2; exit 1;
}
mkdir -p "$output"
output="$(cd "$output" && pwd -P)"
git clone --local --no-hardlinks --no-checkout "$kernel_root" "$output/KernelSource"
git -C "$output/KernelSource" checkout --detach "$base"
git -C "$output/KernelSource" apply --check "$patch"
git -C "$output/KernelSource" apply "$patch"
ln -s "$(cd "$kernel_root/third_party/dist" && pwd -P)" "$output/KernelSource/third_party/dist"
(
  cd "$output/KernelSource"
  export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-13.0}"
  CARGO_TARGET_DIR="$output/KernelTarget" cargo build --locked --release -p erika_capi
) > "$output/kernel-build.log" 2>&1

git clone --local --no-hardlinks "$native_root" "$output/NativeSource"
cp -R "$native_root/Packages/ErikaKit/Vendor" "$output/NativeSource/Packages/ErikaKit/Vendor"
cmp "$output/KernelSource/crates/erika_capi/include/erika.h" \
    "$output/NativeSource/Packages/ErikaKit/Sources/CErika/include/erika.h"
slice="$output/NativeSource/Packages/ErikaKit/Vendor/Erika.xcframework/macos-arm64"
cp "$output/KernelTarget/release/liberika_capi.a" "$slice/liberika_capi.macos-only.a"
python3 - "$output/NativeSource" <<'PY'
from pathlib import Path
import sys
root = Path(sys.argv[1])
version = root / 'Packages/ErikaKit/Sources/ErikaKit/ErikaVersion.swift'
version.write_text('// Generated by build-macos-hdr-fixed.sh; local patched kernel.\n'
                   'public enum ErikaVersion { public static let tag = "v0.3.6+macos.hdr.dev" }\n')
marker = root / 'Packages/ErikaKit/Vendor/Erika.xcframework/.erika-version'
marker.write_text('v0.3.6+macos.hdr.dev\n')
PY

"$repo_root/Scripts/build-apple-dylib.sh" "$output" > "$output/core-build.log" 2>&1
xcodebuild -project "$output/NativeSource/OcPlayer.xcodeproj" -scheme OcPlayer-macOS \
  -configuration Debug -destination 'platform=macOS,arch=arm64' \
  -derivedDataPath "$output/DerivedData" -quiet CODE_SIGNING_ALLOWED=NO \
  GIT_COMMIT_HASH="$(git -C "$native_root" rev-parse --short HEAD)+macos-hdr" build \
  > "$output/macos-build.log" 2>&1
app="$output/DerivedData/Build/Products/Debug/OcPlayer.app"
"$repo_root/Scripts/embed-macos-core.sh" "$app" "$output/libocp_ffi.dylib" > "$output/embed.log" 2>&1
python3 - "$repo_root" "$native_root" "$output" "$base" <<'PY'
from pathlib import Path
import hashlib, json, subprocess, sys
core, native, output, base = sys.argv[1:]
out = Path(output)
def sha(path): return hashlib.sha256(Path(path).read_bytes()).hexdigest()
receipt = dict(coreCommit=subprocess.check_output(['git','-C',core,'rev-parse','HEAD'],text=True).strip(),
               nativeCommit=subprocess.check_output(['git','-C',native,'rev-parse','HEAD'],text=True).strip(),
               kernelBase=base, kernelVersion='v0.3.6+macos.hdr.dev', architecture='arm64',
               patchSha256=sha(Path(core)/'patches/liberika/v0.3.6-macos-hdr.patch'),
               kernelArchiveSha256=sha(out/'KernelTarget/release/liberika_capi.a'),
               coreLibrarySha256=sha(out/'libocp_ffi.dylib'))
(out/'build-receipt.json').write_text(json.dumps(receipt,indent=2)+'\n')
PY
echo "$app"
