import Foundation

// Freeze the reference runtime's matching semantics rather than approximating
// fullwidth conversion with NFKC or dropping every non-alphanumeric scalar.
func ranges(_ values: [UInt32]) -> [(UInt32, UInt32)] {
    var result: [(UInt32, UInt32)] = []
    for value in values {
        if let last = result.last, last.1 + 1 == value {
            result[result.count - 1].1 = value
        } else { result.append((value, value)) }
    }
    return result
}
func printRanges(_ name: String, _ values: [UInt32]) {
    print("pub const \(name): &[(u32, u32)] = &[")
    for (low, high) in ranges(values) {
        print("    (0x\(String(low, radix: 16)), 0x\(String(high, radix: 16))),")
    }
    print("];")
}
func printMap(_ name: String, _ values: [(UInt32, [UInt32])]) {
    print("pub const \(name): &[(u32, &[u32])] = &[")
    for (key, value) in values {
        print("    (0x\(String(key, radix: 16)), &[\(value.map { "0x" + String($0, radix: 16) }.joined(separator: ", "))]),")
    }
    print("];")
}
var excluded: [UInt32] = [], trimming: [UInt32] = [], numeric: [UInt32] = []
var lower: [(UInt32, [UInt32])] = [], width: [(UInt32, [UInt32])] = []
let removal = CharacterSet.punctuationCharacters.union(.symbols).union(.whitespacesAndNewlines)
var scalars: [Unicode.Scalar] = []
for value in UInt32(1)...UInt32(0x10FFFF) {
    guard let scalar = Unicode.Scalar(value) else { continue }
    scalars.append(scalar)
    if removal.contains(scalar) { excluded.append(value) }
    if CharacterSet.whitespacesAndNewlines.contains(scalar) { trimming.append(value) }
    if Character(String(scalar)).isNumber { numeric.append(value) }
    let mapped = String(scalar).lowercased().unicodeScalars.map(\.value)
    if mapped != [value] { lower.append((value, mapped)) }
}
for offset in stride(from: 0, to: scalars.count, by: 4096) {
    let chunk = Array(scalars[offset..<min(offset + 4096, scalars.count)])
    let source = chunk.map(String.init).joined(separator: "\0")
    let transformed = source.applyingTransform(.fullwidthToHalfwidth, reverse: false) ?? source
    let parts = transformed.components(separatedBy: "\0")
    precondition(parts.count == chunk.count)
    for (scalar, part) in zip(chunk, parts) {
        let mapped = part.unicodeScalars.map(\.value)
        if mapped != [scalar.value] { width.append((scalar.value, mapped)) }
    }
}
